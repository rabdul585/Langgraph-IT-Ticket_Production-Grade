if __name__ == "__main__":
    # Sample prompt that would be sent to the LLM (represents user input)
    prompt = "Classify this ticket: My order hasn't arrived after 2 weeks!"
    # Sample response from the LLM (represents model output)
    # In real usage, this would be actual JSON classification output
    response = '{"issue_category": "delivery_issue", "priority": "high"}'

    # Count tokens in the prompt using the default gpt-4o-mini tokenizer
    # This simulates what would happen before sending to OpenAI
    in_tokens = count_tokens(prompt)
    
    # Count tokens in the response using the same tokenizer
    # In production, this would come from OpenAI's usage metadata
    out_tokens = count_tokens(response)
    
    # Calculate the cost for this single LLM call
    # record_to_session defaults to True, so this updates the session tracker
    cost = calculate_cost("gpt-4o-mini", in_tokens, out_tokens)

    # Display the breakdown of tokens and costs for this single call
    print(f"Input tokens : {cost.input_tokens}")
    print(f"Output tokens: {cost.output_tokens}")
    print(f"Input cost   : ${cost.input_cost_usd:.6f}")
    print(f"Output cost  : ${cost.output_cost_usd:.6f}")
    print(f"Total cost   : ${cost.total_cost_usd:.6f}")
    
    # Display the cumulative session totals after this call
    # Demonstrates how session tracker accumulates costs across calls
    print(f"Session total: {session_tracker.summary}")
